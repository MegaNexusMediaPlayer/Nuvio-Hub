_SORTED_KEYS = sorted(STRINGS.keys(), key=len, reverse=True)

# v3.9.17: tr() perf + correctness pass.
# Two-tier matching keeps exact lookups O(1) and confines the slower substring
# fallback to phrase-shaped keys. Short standalone words like 'تركي' or 'أفلام'
# are dangerous as substring matches because they appear inside longer Arabic
# words (e.g. 'تركية', 'الأفلام'); restricting substring fallback to keys with
# whitespace or punctuation prevents accidental in-word corruption.
#
# A key is treated as "safe for substring" if it satisfies any of:
#   - contains a space, comma, period, colon, ellipsis, bracket, or %
#   - length >= 15 chars (long enough that accidental in-word collision is
#     extremely unlikely in practice)
# Everything else is exact-match-only.
def _is_safe_for_substring(key):
    if len(key) >= 15:
        return True
    if not key:
        return False
    for ch in key:
        if ch in ' \t,.:;!?…[]()%·\n':
            return True
    return False

_SUBSTRING_KEYS = tuple(k for k in _SORTED_KEYS if _is_safe_for_substring(k))


_TR_MEMO = {}
_TR_MEMO_LIMIT = 4096


def tr(text):
    if text is None:
        return text
    if not isinstance(text, str) or not is_english():
        return text
    # --- dexhub-401-patch --- memoised cold path
    hit = _TR_MEMO.get(text)
    if hit is not None:
        return hit
    result = _tr_compute(text)
    if len(_TR_MEMO) < _TR_MEMO_LIMIT:
        _TR_MEMO[text] = result
    return result


def _tr_compute(text):
    # Hot path: exact dict lookup is O(1) and handles ~all UI labels.
    exact = STRINGS.get(text)
    if exact is not None:
        return exact
    # Cold path: substring substitution for composed strings only. Short
    # standalone keys are intentionally skipped to avoid corrupting partial
    # word matches in longer Arabic text.
    out = text
    for key in _SUBSTRING_KEYS:
        if key in out:
            out = out.replace(key, STRINGS[key])
    return out


def trf(template, *args, **kwargs):
    translated = tr(template)
    try:
        if args or kwargs:
            return translated % (args if len(args) != 1 else args[0]) if args else translated.format(**kwargs)
        return translated
    except Exception:
        return translated
