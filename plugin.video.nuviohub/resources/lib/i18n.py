def reset_language_cache():
    _TR_MEMO.clear()
    """Force re-read of the ui_language setting on the next current_language() call.

    Call this from a settings-changed hook so language flips apply without restart.
    """
    global _lang_cache
    _lang_cache = None


def current_language():
    global _lang_cache
    if _lang_cache is not None:
        return _lang_cache
    _lang_cache = _read_language_setting()
    return _lang_cache


